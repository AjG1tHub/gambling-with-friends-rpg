export function makeEvent(type, payload = {}, { actor = 'system', ts = Date.now(), roomId = null } = {}) {
  if (!EVENTS[type]) throw new Error(`unknown event type ${type}`);
  return { id: shortId('e'), seq: null, type, roomId, actor, ts, payload };
}
export const isGmActor = (ev) => ev.actor === 'gm' || ev.actor === 'system';
