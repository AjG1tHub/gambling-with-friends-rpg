// Lever curves: the expected return of every game at every value of its governing stat, simulated with the same
// bot and the same adapter the payout report uses. The phones draw these curves so a player can see what their
// Luck 7 is worth on Coin Blade before they stake Health on it.
//
//   node tools/build-lever-curves.mjs [rounds]      → data/lever-curves.json  (default 4000 rounds per stat value)
//
// Expensive (36 games × 10 stat values); run it when a lever or an odds table changes, and commit the JSON.
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { startRound } from '../packages/games/adapter.js';
import { ITEM_DEFS, makeItem } from '../packages/games/items.js';
import { LEVERS } from '../packages/games/levers.js';
import { makeRng } from '../packages/shared/rng.js';
import { B } from '../packages/shared/balance.js';

const here = dirname(fileURLToPath(import.meta.url));
const N = Number(process.argv[2]) || 4000;
const NEUTRAL = { luck: B.stats.neutral, nerve: B.stats.neutral, greed: B.stats.neutral, grit: B.stats.neutral };
const heavy = new Set(['paigow', 'holdem', 'letitride', 'threecard', 'videopoker', 'blackjack']);

function simulate(gameId, stat, n, seed = 20261028) {
  const rng = makeRng(seed), pick = makeRng(seed ^ 0x9e3779b9);
  const stats = { ...NEUTRAL }; stats[LEVERS[gameId].stat] = stat;
  const item = makeItem(null, { gameId, seed: 1 });
  let ret = 0, wins = 0;
  for (let i = 0; i < n; i++) {
    const r = startRound(null, { item, mode: 'health', stake: item.stake, attacker: { id: 'a', name: 'Sim', stats }, target: { id: 't', name: 'Dummy', stats: NEUTRAL }, rng, now: i * 1000 });
    const o = r.play(pick, true); if (!o) throw new Error(`${gameId} did not finish`);
    ret += o.mult; if (o.mult > 1) wins++;
  }
  return { rtp: Math.round(ret / n * 1000) / 1000, win: Math.round(wins / n * 1000) / 1000 };
}

const out = { _about: `Expected return (rtp: total returned per unit staked) and win rate (win: share of rounds paying more than the stake) of every game at each value of its governing stat, ${N} bot-played rounds per point (fewer for the slow table games). Generated by tools/build-lever-curves.mjs; the phones draw the curve so players see what a stat point is worth. Stats run ${B.stats.min}–${B.stats.max}, neutral ${B.stats.neutral}.`, neutral: B.stats.neutral, min: B.stats.min, max: B.stats.max, games: {} };
const t0 = Date.now();
for (const d of ITEM_DEFS) {
  const n = heavy.has(d.gameId) ? Math.min(N, 1500) : N;
  const lever = LEVERS[d.gameId];
  const curve = [];
  for (let s = B.stats.min; s <= B.stats.max; s++) curve.push({ stat: s, ...simulate(d.gameId, s, n) });
  out.games[d.gameId] = { stat: lever.stat, kind: lever.kind, text: lever.text, curve };
  process.stdout.write(`${d.gameId.padEnd(12)} ${curve.map(c => (c.rtp * 100).toFixed(0).padStart(4)).join('')}\n`);
}
const path = join(here, '..', 'data', 'lever-curves.json');
const next = JSON.stringify(out, null, 1);
let prev = ''; try { prev = readFileSync(path, 'utf8'); } catch { /* first run */ }
if (prev !== next) writeFileSync(path, next + '\n');
console.log(`${prev === next ? 'unchanged' : 'wrote'} data/lever-curves.json in ${Math.round((Date.now() - t0) / 1000)} s`);
