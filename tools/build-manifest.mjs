// Writes assets/manifest.json: every asset key → { path, size, kind, group, priority, placeholder, sprite?, meta? },
// plus `sound` (cue → { path, placeholder, seconds }) and `aliases` (other modules' sprite spellings → keys).
// `placeholder` is read from the file itself (PNG tEXt chunk, SVG comment, WAV LIST/INFO comment), never assumed.
// Deterministic: keys are sorted, no timestamps. `build()` returns the JSON text; the CLI writes it.
import { existsSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, buildAssetList, loadData, LAYER_Z, FRAME, BODY_POSES, ARMOUR_POSES, WORN_SLOTS, SECRET_COLOURS, RARITY_COLOURS, FAMILY_COLOURS } from './asset-list.mjs';
import { isPlaceholderFile } from './placeholders.mjs';
import { SAMPLE_RATE } from './sounds.mjs';

export const MANIFEST_PATH = 'assets/manifest.json';

function wavSeconds(buf) {
  // 16-bit mono PCM: find the data chunk length.
  let p = 12; while (p + 8 <= buf.length) { const id = buf.toString('latin1', p, p + 4), len = buf.readUInt32LE(p + 4); if (id === 'data') return Math.round(len / 2 / SAMPLE_RATE * 1000) / 1000; p += 8 + len + (len % 2); }
  return 0;
}
const sortObj = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));

export function build({ rows = null, data = null } = {}) {
  data = data || loadData(); rows = rows || buildAssetList(data);
  const assets = {}, sound = {}, missing = [];
  for (const row of rows) {
    const abs = path.join(ROOT, row.path);
    const exists = existsSync(abs);
    if (!exists) missing.push(row.key);
    const buf = exists ? readFileSync(abs) : null;
    const placeholder = exists ? isPlaceholderFile(buf, row.kind) : null;
    if (row.kind === 'wav') { sound[row.meta.cue] = { path: row.path, placeholder, seconds: exists ? wavSeconds(buf) : 0, music: !!row.meta.music, priority: row.priority }; continue; }
    const entry = { path: row.path, kind: row.kind, group: row.group, size: row.size, priority: row.priority, placeholder, bytes: exists ? statSync(abs).size : 0 };
    if (row.genSize) entry.genSize = row.genSize;
    if (row.name && row.name !== row.key) entry.name = row.name;
    if (row.sprite) entry.sprite = row.sprite;
    if (row.meta) entry.meta = row.meta;
    assets[row.key] = entry;
  }
  // Aliases: the spellings data files use for the same art (bases.json consumables say `item/<id>`).
  const aliases = {};
  for (const key of Object.keys(assets)) { if (key.startsWith('consumables/')) aliases[`item/${key.slice(12)}`] = key; if (key.startsWith('items/')) aliases[`item/${key.slice(6)}`] = key; }
  const counts = {}; for (const r of rows) counts[r.group] = (counts[r.group] || 0) + 1;
  const manifest = {
    _about: 'Generated by tools/build-manifest.mjs from tools/asset-list.mjs. Do not edit; drop real art at the listed path and rerun `npm run gen`. `placeholder` is read from each file (PNG tEXt `gwf-placeholder`, SVG `<!--gwf-placeholder-->`, WAV INFO comment).',
    version: 1,
    sprite: { frame: FRAME, bodyPoses: BODY_POSES, armourPoses: ARMOUR_POSES, layerZ: LAYER_Z, wornSlots: WORN_SLOTS, spritesRoot: 'assets/sprites/' },
    palette: { secretColours: SECRET_COLOURS, rarity: RARITY_COLOURS, family: FAMILY_COLOURS },
    counts: sortObj(counts), total: rows.length, missing: missing.sort(),
    assets: sortObj(assets), sound: sortObj(sound), aliases: sortObj(aliases),
  };
  return JSON.stringify(manifest, null, 1) + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = build(); const abs = path.join(ROOT, MANIFEST_PATH);
  const m = JSON.parse(text);
  if (!existsSync(abs) || readFileSync(abs, 'utf8') !== text) { writeFileSync(abs, text); console.log(`wrote ${MANIFEST_PATH}`); } else console.log(`${MANIFEST_PATH} unchanged`);
  const ph = Object.values(m.assets).filter(a => a.placeholder).length + Object.values(m.sound).filter(s => s.placeholder).length;
  console.log(`${m.total} assets, ${ph} placeholders, ${m.missing.length} missing${m.missing.length ? ': ' + m.missing.slice(0, 10).join(', ') : ''}`);
}
